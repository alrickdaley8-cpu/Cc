import assert from 'node:assert/strict';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium as playwright } from 'playwright-core';
import chromium, { inflate } from '@sparticuz/chromium';

// Chromium's package includes the NSS libraries needed in minimal Linux containers.
const packageDir=resolve(dirname(fileURLToPath(import.meta.resolve('@sparticuz/chromium'))),'..');
const nss=await inflate(resolve(packageDir,'bin/al2023.tar.br'));
const server=await createServer({server:{host:'127.0.0.1',port:0},logLevel:'error'});
await server.listen();
const port=server.httpServer.address().port;
let browser;
try {
  browser=await playwright.launch({executablePath:await chromium.executablePath(),args:chromium.args,headless:true,env:{...process.env,LD_LIBRARY_PATH:`${nss}/lib:${process.env.LD_LIBRARY_PATH||''}`}});
  const page=await browser.newPage({viewport:{width:1280,height:800}});
  page.setDefaultTimeout(12000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`http://127.0.0.1:${port}/`,{waitUntil:'networkidle'});
  assert.match(await page.title(),/Worldforge/);
  assert.equal(await page.locator('canvas').count(),1);
  await page.getByTitle('Pause').click();
  // Select, focus and develop a village while paused: all six visual stages are playable.
  await page.getByRole('button',{name:/Eldoria.*Human kingdom/}).click();
  await page.getByRole('button',{name:'Focus village'}).click();
  assert.match(await page.locator('.map-controls').innerText(),/300%/);
  await page.waitForTimeout(200);const villageBefore=await page.locator('canvas').evaluate(c=>c.toDataURL());
  const advance=page.getByRole('button',{name:'✦ Divine advance'});
  for(let i=0;i<5&&await advance.isEnabled();i++)await advance.click();
  assert.match(await page.locator('.village-detail').innerText(),/HIGHEST TIER REACHED/);
  await page.waitForTimeout(200);const villageAfter=await page.locator('canvas').evaluate(c=>c.toDataURL());assert.ok(villageBefore!==villageAfter,'upgraded buildings change the map');
  await page.getByTitle('Save world').click();const developed=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  assert.equal(developed.cities.find(c=>c.name==='Eldoria').level,6);
  await page.getByTitle('Reset view').click();await page.getByRole('button',{name:'World',exact:true}).click();
  await page.getByTitle('Save world').click();
  const before=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  await page.getByTitle('Grass',{exact:true}).click();await page.mouse.click(500,400);await page.getByTitle('Save world').click();
  const land=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  await page.getByTitle('Shallow water',{exact:true}).click();await page.mouse.click(500,400);await page.getByTitle('Save world').click();
  const flooded=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  assert.ok(flooded.tiles.some((tile,i)=>tile!==land.tiles[i]&&tile==='water'),'terrain painting changes the map');
  await page.getByTitle('Grass',{exact:true}).click();await page.mouse.click(500,400);
  await page.getByTitle('Life',{exact:true}).click();
  await page.getByTitle('Human',{exact:true}).click();
  await page.mouse.click(500,400);
  await page.getByTitle('Save world').click();
  const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  assert.ok(after.units.length>before.units.length,'placing a human adds citizens');
  await page.getByTitle('Inspect',{exact:true}).click();await page.mouse.click(500,400);
  assert.match(await page.locator('.detail-card').last().innerText(),/Activity/);
  await page.getByRole('button',{name:'☆ Favorite'}).click();
  await page.getByTitle('Traits',{exact:true}).click();await page.getByTitle('Immortal',{exact:true}).click();await page.mouse.click(500,400);
  await page.getByTitle('Save world').click();const edited=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  assert.ok(edited.units.some(u=>u.favorite));assert.ok(edited.units.some(u=>u.traits.includes('Immortal')));
  await page.getByTitle('Settings').click();
  const hunger=page.getByRole('switch',{name:'Hunger'});assert.equal(await hunger.getAttribute('aria-checked'),'true');await hunger.click();
  await page.getByRole('button',{name:'Done'}).click();await page.getByTitle('Save world').click();
  await page.getByTitle('Settings').click();await hunger.click();await page.getByRole('button',{name:'Done'}).click();
  await page.getByTitle('Load saved world').click();await page.getByTitle('Settings').click();
  assert.equal(await hunger.getAttribute('aria-checked'),'false','world laws survive save/load');
  await page.getByRole('button',{name:'Done'}).click();
  await page.getByTitle('Zoom in').click();assert.match(await page.locator('.map-controls').innerText(),/120%/);
  const canvasBefore=await page.locator('canvas').evaluate(c=>c.toDataURL());
  await page.keyboard.down('Shift');await page.mouse.move(500,400);await page.mouse.down();await page.mouse.move(550,430,{steps:4});await page.mouse.up();await page.keyboard.up('Shift');
  await page.waitForTimeout(200);const canvasAfter=await page.locator('canvas').evaluate(c=>c.toDataURL());assert.ok(canvasBefore!==canvasAfter,'pan moves the view');
  await page.getByRole('button',{name:'History',exact:true}).click();assert.match(await page.locator('.history-list').innerText(),/world awakens/i);
  // New biomes and monsters participate in the saved simulation.
  await page.getByTitle('Biomes',{exact:true}).click();await page.getByTitle('Enchanted',{exact:true}).click();await page.mouse.click(500,400);
  await page.getByTitle('Monsters',{exact:true}).click();await page.getByTitle('Zombie',{exact:true}).click();await page.mouse.click(500,400);
  await page.getByTitle('Save world').click();const enhanced=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  assert.ok(enhanced.tiles.includes('enchanted'));assert.ok(enhanced.units.some(u=>u.race==='zombie'));
  // The empty preset, seed, JSON export, validation, and import must work together.
  await page.getByTitle('New world').click();await page.getByRole('button',{name:/Empty ocean/}).click();await page.getByLabel('World seed').fill('2024');
  await page.getByRole('button',{name:'Generate world'}).click();await page.getByTitle('Save world').click();
  const blank=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));assert.equal(blank.seed,2024);assert.equal(blank.units.length,0);assert.ok(blank.tiles.every(t=>t==='deep'));
  await page.getByTitle('Settings').click();
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export JSON'}).click();const download=await downloadPromise;assert.equal(download.suggestedFilename(),'worldforge-world.json');
  await page.locator('input[aria-label="Import world file"]').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{"tiles":[]}')});
  await page.getByText('Invalid or unsupported world file').waitFor();
  await page.locator('input[aria-label="Import world file"]').setInputFiles({name:'world.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(enhanced))});
  await page.getByText('World imported successfully').waitFor();await page.getByTitle('Save world').click();const imported=await page.evaluate(()=>JSON.parse(localStorage.getItem('worldforge-save')));
  assert.ok(imported.units.some(u=>u.race==='zombie'));assert.ok(imported.tiles.includes('enchanted'));
  assert.deepEqual(errors,[],'no browser runtime errors');
  console.log('Desktop interactions passed; checking mobile layout...');
  const mobile=page;await mobile.setViewportSize({width:390,height:844});await mobile.reload({waitUntil:'domcontentloaded'});
  assert.equal(await mobile.locator('canvas').count(),1);assert.ok(await mobile.getByTitle('Open world overview').isVisible());
  await mobile.getByTitle('Pan map').click();assert.equal(await mobile.getByTitle('Pan map').getAttribute('aria-pressed'),'true');
  await mobile.getByTitle('Open world overview').click();await mobile.getByTitle('Collapse panel').click();assert.equal(await mobile.locator('.side-panel').count(),0);
  console.log('Browser smoke tests passed: six-tier village advancement, biomes, monsters, world presets, import/export, zoom/pan, and mobile panel.');
} finally {if(browser)await browser.close();await server.close()}
